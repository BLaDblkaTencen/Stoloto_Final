export type SportTheme = (typeof THEMES)[number]['theme'];

/** Подпись темы для подсказки в форме: «Иконку подберём по теме „конный спорт“». */
export const SPORT_THEME_LABELS = Object.fromEntries(
  THEMES.map(({ theme, label }) => [theme, label]),
) as Record<SportTheme, string>;

/** Тема вида спорта по slug; null — ни одно слово не подошло (общая иконка). */
export function sportTheme(slug: string): SportTheme | null {
  const text = ` ${slug} `;
  const found = THEMES.find(({ words }) => words.some((word: string) => text.includes(` ${word}`)));
  return found?.theme ?? null;
}
